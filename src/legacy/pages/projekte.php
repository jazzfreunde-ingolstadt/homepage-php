<a name="youngjazzplayers"></a>
<h2>Sessions der Young-Jazz-Players</h2>

<p>Seit dem Sommer 2006 fördert der Verein der Ingolstädter Jazzfreunde e.&nbsp;V. gezielt den Jazznachwuchs in Ingolstadt. Besonders unterstützt wird diese Arbeit von den Musiklehrern Bernhard Reitberger (Gnadenthal-Gymnasium) und Robert Aichner (Reuchlin-Gymnasium).</p>

<p>Mehrere kostenlose Veranstaltungen, so z.&nbsp;B. bei den Ingolstädter Big Band Nächten und im Bürgerhaus / Diagonal, geben den jungen Musikern eine öffentliche Plattform – und das mit hohem Publikumsinteresse und großartigem Erfolg.</p>

<p>Unterstützt werden die Sessions auch von den Ingolstädter Jazzförderpreisträgern, die in z.&nbsp;T. zuvor stattfindenden Workshops die jungen Musiker an den Jazz heranführen.</p>


<a name="jamsessions"></a>
<h2>Jam Sessions / Offene Bühne</h2>

<p>Startschuss für das neue Baby des Vereins der Ingolstädter Jazzfreunde e.&nbsp;V. war Ende Januar 2008. Die Idee, jeden letzten Sonntag im Monat (mit Ausnahme des August) ambitionierte Jazzmusiker der Region Ingolstadts auf einer Bühne zu vereinigen, entpuppte sich als großer Erfolg.</p>

<p>Eröffnet werden die groovenden Abende von einer Sessionband, die sich meist aus Mitgliedern bekannter regionaler Formationen zusammensetzen. Einsteigen kann jeder! Voraussetzung: Das Instrument muss selbst mitgebracht werden.</p>

<p>Veranstaltungsort für das kostenlose Event ist das Szenelokal „Diagonal“ (<a href="http://www.diagonal-bar.de" title="Diagonal">www.diagonal-bar.de</a>) im Bürgerhaus (<a href="http://www.buergerhaus-ingolstadt.de" title="Bürgerhaus Ingolstadt">www.buergerhaus-ingolstadt.de</a>).</p>

<a name="jazzliteratur"></a>
<h2>Jazz &amp; Literatur</h2>

<p>Seit 2012 veranstaltet der Verein in Zusammenarbeit mit dem Stadttheater Ingolstadt die erfolgreiche Reihe „Jazz &amp; Literatur“. Bei ca. vier Veranstaltungen pro Jahr werden an einem Sonntag Vormittag von Schauspielern literarische Kostbarkeiten vorgetragen und mit thematisch passender Live-Jazzmusik angereichert. Übrigens: Mitglieder des Vereins erhalten an der Abendkasse gegen Vorlage ihres Mitgliedsausweises 10% Ermäßigung auf die Eintrittskarten.</p>

<a name="workshops"></a>
<h2>Workshops</h2>

<p>Ziel des Vereins der Ingolstädter Jazzfreunde e.&nbsp;V. ist die Förderung der Ingolstädter Jazzszene, v.&nbsp;a. des jazzhungrigen Nachwuchses. Zu diesem Zwecke werden Workshops für Schüler und Studenten angeboten, in denen Stilistik, Spieltechniken, Timing, Groove und Rhythmik des Jazz sowie ein Einstieg in die Improvisation geübt werden. Namhafte Ingolstädter Jazzmusiker, zum Teil Jazzförderpreisträger der Stadt, nehmen sich dabei der Jugendlichen an. Die Ergebnisse werden in den danach stattfindenden Sessions der Young Jazz Players einem breiteren Publikum vorgestellt.</p>

<p>Anfang 2015 wurde mit dem Street Marching Band Workshop eine neue Möglichkeit für Ingolstädter Kinder und Jugendliche geschaffen, außerhalb der Schulbands gemeinsam Musik zu machen. Die Jazzfreunde Ingolstadt, der Verein „Künstler an die Schulen“ und die „Kunst- und Kulturbastei“ haben mit Unterstützung des Netzwerks bayerischer Städte Stadtkultur dieses längerfristig gedachte Projekt ins Leben gerufen.</p>

<a name="diagonal"></a>
<h2>Unterstützung der Jazzkonzertreihe im Diagonal</h2>

<p>Die Jazzkneipe Ingolstadts heißt Diagonal (<a href="http://www.diagonal-bar.de" title="Diagonal">www.diagonal-bar.de</a>)! Zahlreiche Konzerte belegen die Ausnahmestellung dieses Szenelokals im Bürgerhaus (<a href="http://www.buergerhaus-ingolstadt.de" title="Bürgerhaus Ingolstadt">www.buergerhaus-ingolstadt.de</a>). Seit 1993 geben sich in der Konzertreihe „Jazz &amp; More“ internationale Spitzenmusiker und Stars des Jazz die Klinke in die Hand, u.&nbsp;a. Billy Cobham, Buddy Miles, Joe Zawinul, Steve Khan, Allan Hol, Mike Stern, Wolfgang Haffner, Bob Mintzer, Tuck&nbsp;&amp; Patti. Der Verein der Ingolstädter Jazzfreunde e.&nbsp;V. unterstützt diese Veranstaltungsreihe durch Werbung in seinem Newsletter und auf seiner Homepage.</p>

<a name="jazztage"></a>
<h2>Unterstützung der Ingolstädter Jazztage</h2>

<p>Das Highlight im Jazzkalender Ingolstadts! Organisiert wird dieser Megaevent (<a href="http://www.ingolstadt.de/jazztage" title="Ingolstädter Jazztage">www.ingolstadt.de/jazztage</a>) vom Ehrenmitglied des Vereins der Ingolstädter Jazzfreunde e.&nbsp;V. Jan Rottau und seinem Team. Seit 2013 organisieren die Jazzfreunde in Zusammenarbeit mit dem Kulturamt ein Event im Rahmen der Jazztage: „Jazzfreunde e.&nbsp;V. presents“: Unter dem Motto „Jazz vom Feinsten aus deutschen Landen“ treten in einem Doppelkonzert innovative deutsche Jazzformationen (regional und überregional) auf. Übrigens: Mitglieder des Vereins erhalten kostenlose Eintrittskarten für dieses Konzert (Bonuskonzert)! Weiterhin findet im Rahmen der Jazztage eine „Young Players Session“ im Diagonal statt.</p>

