<h1>Satzung Jazzfreunde Ingolstadt</h1>

<h2>§&nbsp;1&emsp;Name und Anschrift des Vereins</h2>
<ol class="satzung">
  <li>Der Verein trägt den Namen „Jazzfreunde Ingolstadt“.</li>
  <li>Der Verein hat seinen Sitz in Ingolstadt.</li>
  <li>Der Verein ist in das Vereinsregister einzutragen und trägt den Namenszusatz
    „eingetragener Verein (e.V.)“</li>
</ol>

<h2>§&nbsp;2&emsp;Zweck des Vereins</h2>
<ol class="satzung">
  <li>Zweck des Vereins ist die Förderung der Kunst und Kultur. Dieser Zweck wird insbesondere verwirklicht durch die materielle und ideelle Förderung der Jazztage Ingolstadt und durch künstlerische und kulturelle Aktivitäten im Jazzbereich.</li>
  <li>Der Verein ist selbstlos tätig und verfolgt nicht in erster Linie eigenwirtschaftliche Zwecke.</li>
  <li>Mittel des Vereins dürfen nur für die satzungsmäßigen Zwecke verwendet werden. Die Mitglieder erhalten keine Zuwendungen aus Mitteln des Vereins.</li>
  <li>Es darf keine Person durch Ausgaben, die dem Zweck der Körperschaft fremd sind, oder durch unverhältnismäßig hohe Vergütung begünstigt werden.</li>
</ol>

<h2>§&nbsp;3&emsp;Geschäftsjahr</h2>
<ul class="satzung">
  <li>Das Geschäftsjahr ist das Kalenderjahr.</li>
</ul>

<h2>§&nbsp;4&emsp;Mitgliedschaft</h2>
<ol class="satzung">
  <li>Mitglied des Vereins kann jede natürliche oder juristische Person und Vereinigung sonstiger Art des öffentlichen oder privaten Rechts werden.</li>
  <li>Der Beitritt erfolgt durch schriftliche Beitrittserklärung und Annahme durch den Vorstand.</li>
  <li>Die Ablehnung der Aufnahme durch den Vorstand ist nicht anfechtbar.</li>
  <li>Die Mitgliedschaft erlischt</li>
  <ol type="a">
    <li>bei natürlichen Personen durch Tod, bei juristischen Personen und Personenvereinigungen durch Liquidation oder Insolvenz</li>
    <li>durch schriftliche Austrittserklärung gegenüber dem Vorstand unter Einhaltung einer Frist von drei Monaten</li>
    <li>durch Ausschluss auf Grund eines Beschlusses des Vorstands, wenn das Mitglied seine Pflichten dem Verein gegenüber verletzt, insbesondere wenn es Zwecken oder Grundsätzen des Vereins zuwider handelt oder trotz zweimaliger Mahnung seinen Beitragsverpflichtungen nicht nachkommt.</li>
  </ol>
  </li>
</ol>

<h2>§&nbsp;5&emsp;Mitgliedsbeiträge</h2>
<ol class="satzung">
  <li>Die Höhe des jährlichen Mitgliedsbeitrags liegt derzeit bei
    <ul class="satzung">
      <li>50&nbsp;€ Regelbeitrag</li>
      <li>20&nbsp;€ für Schüler und Studenten</li>
      <li>60&nbsp;€ für Familien</li>
      <li>500&nbsp;€ für juristische Personen</li>
    </ul>
  </li>
  <li>Die Höhe der jährlichen Mindestbeiträge wird von der Mitgliederversammlung festgesetzt.</li>
  <li>Mitglieder die mindestens das Zehnfache des für sie geltenden Jahresbeitrags entrichten, erhalten die Ehrenbezeichnung „Förderer“.</li>
  <li>Die jährlichen Beitragsleistungen sind bis spätestens 31.03. jedes Jahres, für neu eintretende Mitglieder innerhalb eines Monats nach Eintritt fällig. Bei Eintritt während eines Kalenderjahrs werden die Beitragsleitungen für das gesamte Geschäftsjahr erhoben.</li>
</ol>

<h2>§&nbsp;6&emsp;Stimmrecht</h2>
<ul class="satzung">
  <li>Die Mitglieder haben das Recht, den Mitgliederversammlungen des Vereins beizuwohnen und in diesen ihr Stimmrecht auszuüben. Jedes Mitglied hat nur eine Stimme.</li>
  <li>Juristische Personen und Vereinigungen üben ihre Rechte durch eine von ihnen zu benennende Einzelperson aus.</li>
</ul>

<h2>§&nbsp;7&emsp;Organe des Vereins</h2>
<ul class="satzung">
  <li>Organe des Vereins sind
    <ul>
      <li>der Vorstand</li>
      <li>der Beirat</li>
      <li>die Mitgliederversammlung</li>
    </ul>
  </li>
</ul>

<h2>§&nbsp;8&emsp;Der Vorstand / Der Beirat</h2>
<ol class="satzung">
  <li>Der Vorstand besteht aus bis zu fünf Mitgliedern.</li>
  <li>Ihm gehören an:
    <ul>
      <li>der/die erste Vorsitzende</li>
      <li>zwei stellvertretende Vorsitzende</li>
      <li>der/die Schriftführer/-in</li>
      <li>der/die Schatzmeister/-in</li>
    </ul>
  </li>
  <li>Die Vorstandsmitglieder werden von der Mitgliederversammlung aus dem Kreis der Mitglieder auf die Dauer von zwei Jahren gewählt. Sie bleiben jedoch bis zur Neuwahl im Amt.<br />
    Die Funktion/en des Schriftführers und/oder des Schatzmeisters kann/können auch vom Vorstandsvorsitzenden oder einem stellvertretenden Vorsitzenden übernommen werden.</li>
  <li>Vorstand im Sinne des §&nbsp;26&nbsp;BGB sind der/die erste Vorsitzende, sowie die zwei stellvertretenden Vorsitzenden. Zwei dieser Vorstandsmitglieder vertreten den Verein außergerichtlich und gerichtlich. Der Vorsitzende vertritt den Verein außergerichtlich und gerichtlich alleine.</li>
  <li>Die Amtsdauer der Mitglieder des Vorstands beginnt mit der Wahl und endet mit der Neuwahl, sofern bei der Wahl nichts Anderes bestimmt ist. Erstes Jahr ist das zur Zeit ablaufende Geschäftsjahr. Ersatzwahlen gelten für die Amtsdauer der ersetzten Mitglieder.</li>
  <li>Der Vorstand im Sinne des §&nbsp;8/2 besorgt die Angelegenheiten des Vereins, soweit sie nicht der Mitglieder­versammlung vorbehalten sind. Er trifft die zur Erfüllung des Vereins notwendigen Entscheidungen. Der Vorstand ist beschlussfähig, wenn mindestens zwei Mitglieder des Vorstandes im Sinne des §&nbsp;8/2 bei der Beschlussfassung anwesend sind. Bei Stimmengleichheit entscheidet die Stimme des Vorsitzenden.</li>
  <li>Der Vorstand übt seine Tätigkeiten ehrenamtlich aus.</li>
  <li>Der Vorstand wählt aus den Vereinsmitgliedern bis zu neun Beiräte. Der Beirat unterstützt den Vorstand bei den Beratungen und Beschlussfassungen im Rahmen der Vorstandssitzungen. Die Beiräte haben nur beratende Funktionen, sie haben bei den Vorstandssitzungen kein Stimmrecht, sie vertreten den Verein nicht nach außen. Mit jeder Neuwahl des Vorstandes sind auch dei Beiräte neu zu wählen.</li>
  <li>Zu den Sitzungen des Vorstands werden dessen Mitglieder und die Beriäte vom/von der ersten Vorsitzenden unter Bekanntgabe der Tagesordnung schriftlich berufen. Über die Verhandlungen und Beschlüsse des Vorstands ist eine Niederschrift anzufertigen. Eine Schriftliche Beschlussfassung im Umlaufverfahren ist möglich.</li>
</ol>

<h2>§&nbsp;9&emsp;Mitgliederversammlung</h2>
<ol class="satzung">
  <li>Die ordentliche Mitgliederversammlung ist alljährlich, spätestens im dritten Quartal des Geschäftsjahrs einzuberufen. Sie wird vom Vorsitzenden geleitet.</li>
  <li>Die Einladung zu den Mitgliederversammlungen erfolgt schriftlich unter Mitteilung der Tagesordnung unter Wahrung einer Frist von 14 Tagen. Der Tag der Einberufung und der Tag der Versammlung sind hierbei nicht mitzurechnen.</li>
  <li>Der Mitgliederversammlung obliegen:
    <ol type="a">
      <li>die Entgegennahme des Berichts über das abgelaufene Geschäftsjahr</li>
      <li>die Abnahme der Jahresrechnung und die Entlastung des Vorstands</li>
      <li>die Wahlen zum Vorstand</li>
      <li>die Wahl zweier Kassenprüfer, die nicht dem Vorstand angehören</li>
      <li>Beschlussfassung über Anträge des Vorstands und aus der Mitte der Mitgliederver­sammlung</li>
      <li>Festlegung des Mindestbeitrags</li>
    </ol>
  </li>
  <li>In der Mitgliederversammlung hat jedes Mitglied eine Stimme.</li>
  <li>Bei den Wahlen entscheidet das Los, wenn Stimmengleichheit vorliegt.</li>
  <li>Anträge zur Tagesordnung sind spätestens eine Woche vor dem Tag der Mitgliederver­sammlung beim Vorstand schriftlich einzureichen.</li>
</ol>

<h2>§&nbsp;10&emsp;Außerordentliche Mitgliederversammlung</h2>
<ul class="satzung">
  <li>Der Vorstand beruft eine außerordentliche Mitgliederversammlung ein, wenn ein Viertel der Mitglieder des Vereins diese schriftlich beantragen. Die Mitgliederversammlung ist unabhängig von der Zahl der erschienenen Mitglieder beschlussfähig.</li>
</ul>

<h2>§&nbsp;11&emsp;Beschlussfassung</h2>
<ul class="satzung">
  <li>Die Beschlüsse der Mitgliederversammlung werden mit einfacher Stimmenmehrheit der anwesenden Mitglieder gefasst.</li>
</ul>

<h2>§&nbsp;12&emsp;Beurkundung der Beschlüsse</h2>
<ol class="satzung">
  <li>Über die in den Mitgliederversammlungen gefassten Entschlüsse ist eine Niederschrift aufzunehmen.</li>
  <li>Die Niederschrift ist von dem/der Vorsitzenden der Versammlung und dem/der Schriftführer/-in zu unterzeichnen.</li>
  <li>Jedes Vereinsmitglied ist berechtigt, die Niederschrift über die Mitgliederversamm­lung einzusehen.</li>
</ol>

<h2>§&nbsp;13&emsp;Satzungsänderung</h2>
<ul class="satzung">
  <li>Eine Änderung der Satzung kann nur in einer Mitgliederversammlung mit einer Mehrheit von drei Vierteln der Anwesenden Mitglieder beschlossen werden. In der Einladung zur Mitgliederversammlung ist die vorgeschlagene Satzungsänderung mitzuteilen.</li>
</ul>

<h2>§&nbsp;14&emsp;Anfechtung von Beschlüssen</h2>
<ul class="satzung">
  <li>Eine Anfechtung von Beschlüssen des Vorstands oder der Mitgliederversammlung findet, sofern eine solche nach dieser Satzung zulässig ist, nur innerhalb eines Monats nach der Beschlussfassung statt.</li>
</ul>

<h2>§&nbsp;15&emsp;Auflösung des Vereins</h2>
<ol class="satzung">
  <li>Die Auflösung des Vereins durch die Mitgliederversammlung kann nur mit der in §&nbsp;13 Satz&nbsp;1 festgelegten Mehrheit erfolgen. In der Tagesordnung in muss die Absicht der Auflösung angegeben sein.</li>
  <li>Bei der Auflösung des Vereins oder bei Wegfall steuerbegünstigter Zwecke fällt das Vermögen an die Stadt Ingolstadt, die es unmittelbar und ausschließlich für gemeinnützige Zwecke im Sinne dieser Satzung zu verwenden hat.</li>
</ol>

<p class="small">Vorstehende Satzung ist errichtet am 17.02.2005 und geändert am 22.02.2011 und am 12.02.2014</p>

